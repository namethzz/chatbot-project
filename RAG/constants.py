# ชื่อจังหวัดที่เป็นคำธรรมดาด้วย ("ได้เลย", "ตากแดด", "แพร่ระบาด")
# → นับเป็นจังหวัดก็ต่อเมื่อมี "จังหวัด" / "จ." นำหน้าเท่านั้น
AMBIGUOUS_PROVINCES = ['เลย', 'ตาก', 'แพร่']


def find_province(text: str):
    """คืนชื่อจังหวัดแรกที่เจอในข้อความ หรือ None"""
    for prov in ALL_PROVINCES:
        if prov in AMBIGUOUS_PROVINCES:
            if re.search(rf'(?:จังหวัด|จ\.)\s*{prov}', text):
                return prov
        elif prov in text:
            return prov
    return None


# ชื่อพืชที่สะกดผิดในข้อมูลดิบ → ชื่อมาตรฐาน
CROP_ALIASES = {
    'สับประรด': 'สับปะรด',
    'อราบิก้า': 'อาราบิก้า',
}


def normalize_thai(text: str) -> str:
    """แก้ปัญหาการพิมพ์ภาษาไทยที่หน้าตาเหมือนกันแต่เป็นคนละตัวอักษร"""
    text = text.replace('เเ', 'แ')            # เ + เ  → แ
    text = text.replace('\u0e4d\u0e32', '\u0e33')  # ํ + า  → ำ (สระอำที่พิมพ์แยกตัว)
    for wrong, right in CROP_ALIASES.items():
        text = text.replace(wrong, right)
    return text
